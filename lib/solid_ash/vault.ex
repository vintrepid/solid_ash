defmodule SolidAsh.Vault do
  @moduledoc """
  Cloak vault used by SolidAsh encrypted Ash resources.

  Host applications must configure a 32-byte AES-GCM key:

      config :solid_ash, SolidAsh.Vault,
        ciphers: [
          default: {
            Cloak.Ciphers.AES.GCM,
            tag: "AES.GCM.V1",
            key: Base.decode64!(System.fetch_env!("SOLID_ASH_VAULT_KEY_BASE64"))
          }
        ]

  The key is intentionally not generated by the library. Production systems
  should source it from a secrets manager and rotate by adding new tagged
  AES-GCM ciphers before retiring old ones. Every configured cipher must be
  exactly `Cloak.Ciphers.AES.GCM`, including old decryptors retained for rotation.
  Cipher labels and tags must be unique, keys must be 32-byte binaries, and
  `:iv_length` must be 12 or 16 bytes (the default is 16). Tags must be nonempty
  binaries of at most 255 bytes. Unknown or duplicate configuration options are
  rejected rather than ignored.

  CTR, legacy and custom cipher modules are not supported. Existing CTR data
  must be migrated and verified separately before adopting this version; this
  library provides no fallback decryptor or automatic data migration.

  The final configuration is checked at startup, caching, hot upgrade and every
  encrypt/decrypt operation. Invalid configuration and failed ciphertext
  authentication return sanitized errors without key or ciphertext contents.
  `validate_configuration/1` can inspect another vault's prepared configuration,
  but does not attest that arbitrary callbacks will keep enforcing it.

  Because the running server holds this key,
  this vault provides encryption at rest rather than end-to-end encryption.
  A future client-encrypted mode would keep content keys under user control and
  upload ciphertext; it is a separate protocol and does not change this vault's
  key ownership.
  """

  use Cloak.Vault, otp_app: :solid_ash

  alias SolidAsh.Vault.CiphertextError

  @configuration_error "SolidAsh.Vault requires a nonempty, uniquely tagged AES-GCM-only configuration"
  @configuration_keys [:ciphers, :json_library, :vault]
  @cipher_keys [:key, :tag, :iv_length]

  @doc """
  Validates a final prepared Cloak configuration without starting a vault.

  Every cipher, including non-default decryptors, is checked. Returns only a
  sanitized error; configuration, keys and tags are never included in it.
  This is not an attestation of another vault's callback implementation.
  """
  @spec validate_configuration(term()) :: :ok | {:error, Exception.t()}
  def validate_configuration(config) do
    if keyword_options?(config, @configuration_keys) and
         valid_optional_module?(config, :json_library) and
         valid_optional_module?(config, :vault) and
         valid_ciphers?(Keyword.get(config, :ciphers)) do
      :ok
    else
      {:error, configuration_error()}
    end
  end

  @doc """
  Validates the configuration actually cached by the running SolidAsh vault.

  A vault that has not started returns `Cloak.VaultNotStarted`. Application
  configuration is not a substitute for checking this active configuration.
  """
  @spec validate_runtime_configuration() :: :ok | {:error, Exception.t()}
  def validate_runtime_configuration do
    with {:ok, _config} <- validated_config(), do: :ok
  end

  @doc "The version of this vault's enforced AES-GCM-only security contract."
  def security_policy_version, do: 1

  # Cloak merges startup options before init. Check the option containers too,
  # so malformed host input cannot fail by printing an inspected config/key.
  def start_link(options \\ []) do
    app_config = Application.get_env(:solid_ash, __MODULE__, [])

    if keyword_options?(app_config, @configuration_keys) and
         keyword_options?(options, @configuration_keys) do
      config = Keyword.merge(app_config, options)

      with :ok <- validate_configuration(config),
           {:ok, pid} <- GenServer.start_link(__MODULE__, config, name: __MODULE__) do
        case GenServer.call(pid, :save_config, 10_000) do
          :ok -> {:ok, pid}
          {:error, error} -> {:error, error}
        end
      end
    else
      {:error, configuration_error()}
    end
  end

  @impl GenServer
  def init(config) do
    case validate_configuration(config) do
      :ok -> {:ok, config}
      {:error, error} -> {:stop, error}
    end
  end

  @impl GenServer
  def handle_call(:save_config, _from, config) do
    case validate_configuration(config) do
      :ok ->
        Cloak.Vault.save_config(@table_name, config)
        {:reply, :ok, config}

      {:error, error} ->
        {:reply, {:error, error}, config}
    end
  end

  @impl GenServer
  def code_change(_version, config, _extra) do
    with :ok <- validate_configuration(config) do
      Cloak.Vault.save_config(@table_name, config)
      {:ok, config}
    end
  end

  @impl Cloak.Vault
  def encrypt(plaintext) do
    with {:ok, config} <- validated_config() do
      encrypt_safely(fn -> Cloak.Vault.encrypt(config, plaintext) end)
    end
  end

  @impl Cloak.Vault
  def encrypt(plaintext, label) do
    with {:ok, config} <- validated_config() do
      encrypt_safely(fn -> Cloak.Vault.encrypt(config, plaintext, label) end)
    end
  end

  @impl Cloak.Vault
  def encrypt!(plaintext), do: unwrap!(encrypt(plaintext))

  @impl Cloak.Vault
  def encrypt!(plaintext, label), do: unwrap!(encrypt(plaintext, label))

  @impl Cloak.Vault
  def decrypt(ciphertext) do
    with {:ok, config} <- validated_config() do
      decrypt_safely(fn -> Cloak.Vault.decrypt(config, ciphertext) end)
    end
  end

  @impl Cloak.Vault
  def decrypt!(ciphertext), do: unwrap!(decrypt(ciphertext))

  @impl Cloak.Vault
  def json_library do
    with {:ok, config} <- validated_config() do
      Keyword.get(config, :json_library, Jason)
    end
  end

  defp validated_config do
    with {:ok, config} <- Cloak.Vault.read_config(@table_name),
         :ok <- validate_configuration(config) do
      {:ok, config}
    end
  rescue
    _error -> {:error, configuration_error()}
  end

  defp encrypt_safely(operation) do
    case operation.() do
      {:ok, ciphertext} when is_binary(ciphertext) -> {:ok, ciphertext}
      _other -> {:error, CiphertextError.exception([])}
    end
  rescue
    _error -> {:error, CiphertextError.exception([])}
  end

  defp decrypt_safely(operation) do
    # Cloak 1.1.4 returns {:ok, :error} when OTP rejects an authentication tag.
    # No non-binary result is ever accepted as successfully decrypted content.
    case operation.() do
      {:ok, plaintext} when is_binary(plaintext) -> {:ok, plaintext}
      _other -> {:error, CiphertextError.exception([])}
    end
  rescue
    _error -> {:error, CiphertextError.exception([])}
  end

  defp unwrap!({:ok, value}), do: value
  defp unwrap!({:error, error}), do: raise(error)

  defp keyword_options?(options, allowed) do
    is_list(options) and Keyword.keyword?(options) and
      length(Keyword.keys(options)) == length(Enum.uniq(Keyword.keys(options))) and
      Enum.all?(Keyword.keys(options), &(&1 in allowed))
  end

  defp valid_optional_module?(config, key) do
    not Keyword.has_key?(config, key) or
      (is_atom(Keyword.get(config, key)) and Keyword.get(config, key) not in [nil, true, false])
  end

  defp valid_ciphers?(ciphers) do
    is_list(ciphers) and ciphers != [] and Keyword.keyword?(ciphers) and
      Enum.all?(ciphers, fn
        {_label, {Cloak.Ciphers.AES.GCM, options}} -> valid_cipher_options?(options)
        _other -> false
      end) and
      unique?(Keyword.keys(ciphers)) and
      unique?(Enum.map(ciphers, fn {_label, {_module, options}} -> options[:tag] end))
  end

  defp valid_cipher_options?(options) do
    keyword_options?(options, @cipher_keys) and
      is_binary(options[:key]) and byte_size(options[:key]) == 32 and
      is_binary(options[:tag]) and byte_size(options[:tag]) in 1..255 and
      Keyword.get(options, :iv_length, 16) in [12, 16]
  end

  defp unique?(values), do: length(values) == length(Enum.uniq(values))
  defp configuration_error, do: Cloak.InvalidConfig.exception(@configuration_error)
end
